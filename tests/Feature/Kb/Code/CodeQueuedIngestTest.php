<?php

declare(strict_types=1);

namespace Tests\Feature\Kb\Code;

use App\Ai\EmbeddingsResponse;
use App\Jobs\IngestDocumentJob;
use App\Models\KnowledgeChunk;
use App\Models\KnowledgeDocument;
use App\Services\Kb\Chunkers\CodeAstChunker;
use App\Services\Kb\Code\CodeChunkerUnavailableException;
use App\Services\Kb\Code\CodeFileRefusedException;
use App\Services\Kb\Code\TreeSitterBreakPointDriver;
use App\Services\Kb\DocumentIngestor;
use App\Services\Kb\EmbeddingCacheService;
use App\Services\Kb\Pipeline\SourceDocument;
use App\Support\TenantContext;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Storage;
use Mockery;
use Tests\TestCase;

/**
 * The queued saga (IngestDocumentJob → Flow) and the direct path
 * (DocumentIngestor::ingest) re-apply the admission policy to the BYTES, and
 * the chunker driver policy is enforced end to end.
 */
final class CodeQueuedIngestTest extends TestCase
{
    use RefreshDatabase;

    /** @var list<string> */
    private array $embedded = [];

    protected function setUp(): void
    {
        parent::setUp();
        $this->embedded = [];
        $cache = Mockery::mock(EmbeddingCacheService::class);
        $cache->shouldReceive('generate')->andReturnUsing(function (array $texts): EmbeddingsResponse {
            array_push($this->embedded, ...array_values($texts));

            return new EmbeddingsResponse(array_map(static fn () => array_fill(0, 768, 0.0), $texts), 'fake', 'fake-768');
        });
        $cache->shouldReceive('activeTarget')->andReturn(['provider' => 'fake', 'model' => 'fake-768']);
        $this->app->instance(EmbeddingCacheService::class, $cache);

        config([
            'kb.sources.disk' => 'kb',
            'kb.sources.path_prefix' => '',
            'kb.code.chunker_driver' => 'heuristic',
            'kb.code.max_file_bytes' => 4096,
            'kb.code.extra_deny_globs' => [],
        ]);
        Storage::fake('kb');
    }

    protected function tearDown(): void
    {
        TreeSitterBreakPointDriver::forgetProbe();
        parent::tearDown();
        Mockery::close();
    }

    private function runJob(string $path, string $mime = 'text/x-php'): void
    {
        (new IngestDocumentJob('repo', $path, 'kb', null, [], $mime))->handle(app(TenantContext::class));
    }

    public function test_a_job_queued_before_the_flag_was_turned_off_still_completes(): void
    {
        config(['kb.code.ingestion_enabled' => false]);
        Storage::disk('kb')->put('src/A.php', "<?php\nclass A { public function f(): int { return 1; } }\n");

        $this->runJob('src/A.php');

        $doc = KnowledgeDocument::query()->where('source_path', 'src/A.php')->firstOrFail();
        $this->assertSame('code', $doc->source_type);
        $this->assertGreaterThan(0, KnowledgeChunk::query()->where('knowledge_document_id', $doc->id)->count());
    }

    public function test_a_deny_listed_path_that_reached_the_queue_is_refused_without_conversion_or_embedding(): void
    {
        config(['kb.code.ingestion_enabled' => true]);
        Storage::disk('kb')->put('vendor/acme/B.php', "<?php\nclass B {}\n");

        try {
            $this->runJob('vendor/acme/B.php');
            $this->fail('a deny-listed code file must not be ingested');
        } catch (\RuntimeException $e) {
            $this->assertStringContainsString('IngestDocumentFlow', $e->getMessage());
        }

        $this->assertSame(0, KnowledgeDocument::query()->count());
        $this->assertSame([], $this->embedded);
    }

    public function test_oversize_and_generated_files_are_refused_on_their_bytes(): void
    {
        config(['kb.code.ingestion_enabled' => true]);
        Storage::disk('kb')->put('src/big.php', "<?php\n".str_repeat("// padding line to exceed the cap\n", 400));
        Storage::disk('kb')->put('src/gen.go', "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage x\n");

        foreach (['src/big.php' => 'text/x-php', 'src/gen.go' => 'text/x-go'] as $path => $mime) {
            try {
                $this->runJob($path, $mime);
                $this->fail("{$path} must be refused");
            } catch (\RuntimeException) {
                // refused
            }
        }
        $this->assertSame(0, KnowledgeDocument::query()->count());
    }

    public function test_the_direct_ingest_path_applies_the_same_policy(): void
    {
        config(['kb.code.ingestion_enabled' => true]);
        $this->expectException(CodeFileRefusedException::class);

        app(DocumentIngestor::class)->ingest('repo', new SourceDocument('node_modules/x/index.js', 'text/x-javascript', "module.exports = 1;\n", null, null, 'local', []), 'x');
    }

    public function test_secrets_in_a_queued_file_never_reach_the_embedding_provider_or_the_database(): void
    {
        config(['kb.code.ingestion_enabled' => true]);
        $secret = 'ghp_abcdefghijklmnopqrstuvwxyz0123456789';
        Storage::disk('kb')->put('src/C.php', "<?php\n\$t = '{$secret}';\nclass C {}\n");

        $this->runJob('src/C.php');

        $this->assertNotSame([], $this->embedded);
        foreach ($this->embedded as $text) {
            $this->assertStringNotContainsString($secret, $text);
        }
        foreach (KnowledgeChunk::query()->get() as $chunk) {
            $this->assertStringNotContainsString($secret, json_encode($chunk->getAttributes(), JSON_THROW_ON_ERROR));
        }
        $this->assertStringNotContainsString($secret, json_encode(KnowledgeDocument::query()->first()?->getAttributes(), JSON_THROW_ON_ERROR));
    }

    public function test_a_forced_tree_sitter_driver_with_no_helper_fails_the_ingest_loudly(): void
    {
        config([
            'kb.code.ingestion_enabled' => true,
            'kb.code.chunker_driver' => 'tree_sitter',
            'kb.code.helper_path' => sys_get_temp_dir().'/no-such-helper-'.bin2hex(random_bytes(3)).'.mjs',
            'kb.code.probe_ttl' => 0,
        ]);
        TreeSitterBreakPointDriver::forgetProbe();
        Storage::disk('kb')->put('src/D.php', "<?php\nclass D {}\n");

        try {
            $this->runJob('src/D.php');
            $this->fail('forced tree_sitter without a helper must fail the ingest');
        } catch (\RuntimeException) {
            // loud failure
        }
        $this->assertSame(0, KnowledgeDocument::query()->count(), 'nothing is half-ingested');
    }

    public function test_auto_driver_degrades_to_the_heuristic_and_records_it_per_chunk(): void
    {
        config([
            'kb.code.ingestion_enabled' => true,
            'kb.code.chunker_driver' => 'auto',
            'kb.code.helper_path' => sys_get_temp_dir().'/no-such-helper-'.bin2hex(random_bytes(3)).'.mjs',
            'kb.code.probe_ttl' => 0,
        ]);
        TreeSitterBreakPointDriver::forgetProbe();
        Storage::disk('kb')->put('src/E.php', "<?php\nclass E { public function f() {} }\n");

        $this->runJob('src/E.php');

        $chunk = KnowledgeChunk::query()->firstOrFail();
        $this->assertSame('heuristic', $chunk->metadata['chunker']);
    }

    public function test_the_code_chunker_is_the_one_the_registry_resolves(): void
    {
        $this->assertInstanceOf(CodeAstChunker::class, app(\App\Services\Kb\Pipeline\PipelineRegistry::class)->resolveChunker('code'));
        $this->assertTrue(class_exists(CodeChunkerUnavailableException::class));
    }
}
