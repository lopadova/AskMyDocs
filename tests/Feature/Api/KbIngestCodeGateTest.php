<?php

declare(strict_types=1);

namespace Tests\Feature\Api;

use App\Http\Controllers\Api\KbIngestController;
use App\Jobs\IngestDocumentJob;
use Illuminate\Foundation\Testing\RefreshDatabase;
use Illuminate\Support\Facades\Queue;
use Illuminate\Support\Facades\Route;
use Illuminate\Support\Facades\Storage;
use Tests\TestCase;

/**
 * v8.45 / ADR 0035 D7 — POST /api/kb/ingest in BOTH flag states (R43): with
 * code ingestion OFF a `text/x-php` document is the SAME 422 as v8.44; ON it is
 * queued, secrets never reach the KB disk, and policy-refused files are
 * SKIPPED (additive `skipped`) instead of failing the batch.
 */
final class KbIngestCodeGateTest extends TestCase
{
    use RefreshDatabase;

    private const SECRET = 'AKIAIOSFODNN7EXAMPLE';

    protected function setUp(): void
    {
        parent::setUp();
        Storage::fake('kb');
        Route::post('/api/kb/ingest', KbIngestController::class)->name('api.kb.ingest');
        config([
            'kb.sources.disk' => 'kb',
            'kb.sources.path_prefix' => '',
            'kb.ingest.queue' => 'kb-ingest',
            'kb.ingest.default_project' => 'default',
            'kb.code.max_file_bytes' => 4096,
            'kb.code.extra_deny_globs' => [],
        ]);
    }

    /** @return array{documents: list<array<string, mixed>>} */
    private function payload(string $path = 'src/Billing/Invoice.php', string $mime = 'text/x-php', ?string $content = null): array
    {
        return ['documents' => [[
            'project_key' => 'repo',
            'source_path' => $path,
            'mime_type' => $mime,
            'content' => $content ?? "<?php\nclass Invoice { public function total(): int { return 1; } }\n",
        ]]];
    }

    public function test_off_a_code_mime_is_the_v844_422_and_is_not_listed_as_supported(): void
    {
        config(['kb.code.ingestion_enabled' => false]);
        Queue::fake();

        $resp = $this->postJson('/api/kb/ingest', $this->payload())->assertStatus(422);

        $message = (string) $resp->json('errors.documents.0');
        $this->assertStringContainsString('Unsupported mime_type "text/x-php"', $message);
        $this->assertStringNotContainsString('text/x-php', substr($message, (int) strpos($message, 'Supported:')));
        Storage::disk('kb')->assertMissing('src/Billing/Invoice.php');
        Queue::assertNothingPushed();
    }

    public function test_on_a_code_document_is_written_queued_with_its_language_mime_and_listed_as_supported(): void
    {
        config(['kb.code.ingestion_enabled' => true]);
        Queue::fake();

        $this->postJson('/api/kb/ingest', $this->payload())
            ->assertStatus(202)
            ->assertJsonPath('queued', 1)
            ->assertJsonPath('failed', 0)
            ->assertJsonPath('skipped', 0)
            ->assertJsonPath('documents.0.source_type', 'code');

        Storage::disk('kb')->assertExists('src/Billing/Invoice.php');
        Queue::assertPushed(IngestDocumentJob::class, fn (IngestDocumentJob $job): bool => $job->mimeType === 'text/x-php' && $job->relativePath === 'src/Billing/Invoice.php');

        $unsupported = $this->payload('x.cob', 'text/x-cobol');
        $message = (string) $this->postJson('/api/kb/ingest', $unsupported)->assertStatus(422)->json('errors.documents.0');
        $this->assertStringContainsString('text/x-php', $message);
    }

    public function test_on_secrets_never_reach_the_kb_disk(): void
    {
        config(['kb.code.ingestion_enabled' => true]);
        Queue::fake();
        $code = "<?php\n\$aws = '".self::SECRET."';\nclass A {}\n";

        $this->postJson('/api/kb/ingest', $this->payload('src/A.php', 'text/x-php', $code))->assertStatus(202);

        $stored = (string) Storage::disk('kb')->get('src/A.php');
        $this->assertStringNotContainsString(self::SECRET, $stored);
        $this->assertStringContainsString('[REDACTED_SECRET]', $stored);
    }

    public function test_on_policy_refused_files_are_skipped_with_a_reason_and_do_not_fail_the_batch(): void
    {
        config(['kb.code.ingestion_enabled' => true]);
        Queue::fake();
        $payload = ['documents' => [
            $this->payload('src/ok.php')['documents'][0],
            $this->payload('vendor/acme/lib.php')['documents'][0],
            $this->payload('src/big.php', 'text/x-php', str_repeat('// x'."\n", 2000))['documents'][0],
            $this->payload('src/gen.go', 'text/x-go', "// Code generated by protoc. DO NOT EDIT.\npackage x\n")['documents'][0],
            $this->payload('src/.env.json', 'text/x-json', '{"a":1}')['documents'][0],
        ]];

        $resp = $this->postJson('/api/kb/ingest', $payload)->assertStatus(202);

        $resp->assertJsonPath('queued', 1)->assertJsonPath('skipped', 4)->assertJsonPath('failed', 0);
        $reasons = collect($resp->json('documents'))->where('status', 'skipped')->pluck('reason')->all();
        $this->assertStringContainsString('denied_path', $reasons[0]);
        $this->assertStringContainsString('too_large', $reasons[1]);
        $this->assertStringContainsString('generated_file', $reasons[2]);
        $this->assertStringContainsString('denied_path', $reasons[3]);
        Storage::disk('kb')->assertExists('src/ok.php');
        Storage::disk('kb')->assertMissing('vendor/acme/lib.php');
        Storage::disk('kb')->assertMissing('src/big.php');
        Queue::assertPushedTimes(IngestDocumentJob::class, 1);
    }

    public function test_on_a_mime_that_disagrees_with_the_extension_language_is_a_422(): void
    {
        config(['kb.code.ingestion_enabled' => true]);
        Queue::fake();

        $this->postJson('/api/kb/ingest', $this->payload('src/a.php', 'text/x-python'))->assertStatus(422);
        Queue::assertNothingPushed();
    }

    public function test_the_response_shape_for_non_code_batches_is_additive_only(): void
    {
        config(['kb.code.ingestion_enabled' => false]);
        Queue::fake();

        $this->postJson('/api/kb/ingest', ['documents' => [['project_key' => 'p', 'source_path' => 'docs/a.md', 'content' => "# A\n"]]])
            ->assertStatus(202)
            ->assertJsonPath('queued', 1)
            ->assertJsonPath('failed', 0)
            ->assertJsonPath('skipped', 0);
    }
}
