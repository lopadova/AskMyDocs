<?php

declare(strict_types=1);

namespace Tests\Unit\Services\Kb\Code;

use App\Services\Kb\Code\CodeIngestionPolicy;
use App\Services\Kb\Code\CodeVerdict;
use PHPUnit\Framework\Attributes\DataProvider;
use PHPUnit\Framework\Attributes\Test;
use Tests\TestCase;

final class CodeIngestionPolicyTest extends TestCase
{
    private function policy(bool $enabled = true): CodeIngestionPolicy
    {
        config()->set('kb.code.ingestion_enabled', $enabled);
        config()->set('kb.code.max_file_bytes', 2048);
        config()->set('kb.code.extra_deny_globs', []);

        return new CodeIngestionPolicy();
    }

    #[Test]
    public function flag_off_refuses_everything_with_a_stable_reason(): void
    {
        $verdict = $this->policy(false)->assessPath('src/Invoice.php');

        $this->assertFalse($verdict->accepted);
        $this->assertSame(CodeVerdict::DISABLED, $verdict->reason);
    }

    #[Test]
    public function flag_on_accepts_an_ordinary_source_file(): void
    {
        $this->assertTrue($this->policy()->assessPath('src/Billing/Invoice.php', 100)->accepted);
        $this->assertTrue($this->policy()->assessContent('src/a.ts', "export const a = 1;\n")->accepted);
    }

    #[Test]
    public function unsupported_extension_is_refused(): void
    {
        $verdict = $this->policy()->assessPath('README.md');

        $this->assertSame(CodeVerdict::UNSUPPORTED, $verdict->reason);
    }

    /**
     * @return iterable<string, array{string}>
     */
    public static function deniedPaths(): iterable
    {
        yield 'vendor' => ['vendor/laravel/framework/src/Foo.php'];
        yield 'nested vendor' => ['app/Domain/vendor/x.php'];
        yield 'node_modules' => ['web/node_modules/lodash/index.js'];
        yield '.git' => ['.git/hooks/pre-commit.sh'];
        yield 'dist' => ['dist/app.js'];
        yield 'build' => ['build/output.js'];
        yield 'storage' => ['storage/framework/views/x.php'];
        yield 'minified' => ['public/app.min.js'];
        yield 'composer lock' => ['composer.lock'];
        yield 'package lock' => ['package-lock.json'];
        yield 'yarn lock' => ['yarn.lock'];
        yield 'env' => ['.env.json'];
        yield 'pem' => ['certs/server.pem'];
        yield 'key' => ['certs/server.key'];
        yield 'p12' => ['certs/client.p12'];
        yield 'ssh key' => ['home/id_rsa.sh'];
        yield 'case insensitive' => ['Vendor/Foo.php'];
        yield 'backslashes' => ['vendor\\foo\\Bar.php'];
    }

    #[Test]
    #[DataProvider('deniedPaths')]
    public function deny_list_refuses_dependency_trees_build_output_and_credentials(string $path): void
    {
        $policy = $this->policy();

        $this->assertNotNull($policy->deniedBy($path), "{$path} must match the deny-list");
        $this->assertFalse($policy->assessPath($path)->accepted);
    }

    #[Test]
    public function a_directory_that_merely_contains_a_denied_word_is_not_denied(): void
    {
        $policy = $this->policy();

        $this->assertNull($policy->deniedBy('src/vendors/Acme.php'));
        $this->assertNull($policy->deniedBy('src/building/House.php'));
        $this->assertNull($policy->deniedBy('src/Storage.php'));
    }

    #[Test]
    public function operator_globs_can_add_but_never_remove(): void
    {
        $policy = $this->policy();
        config()->set('kb.code.extra_deny_globs', ['legacy/*', '*.generated.ts']);

        $this->assertNotNull($policy->deniedBy('legacy/Old.php'));
        $this->assertNotNull($policy->deniedBy('src/api.generated.ts'));
        // The built-ins stay even when the operator list is empty or hostile.
        config()->set('kb.code.extra_deny_globs', ['!vendor/*', '']);
        $this->assertNotNull($policy->deniedBy('vendor/x.php'));
    }

    #[Test]
    public function oversize_files_are_refused(): void
    {
        $policy = $this->policy();

        $this->assertSame(CodeVerdict::TOO_LARGE, $policy->assessPath('src/big.php', 4096)->reason);
        $this->assertSame(CodeVerdict::TOO_LARGE, $policy->assessContent('src/big.php', str_repeat('a', 4096))->reason);
    }

    #[Test]
    public function binary_content_is_refused(): void
    {
        $verdict = $this->policy()->assessContent('src/blob.php', "<?php\0\1\2 binary");

        $this->assertSame(CodeVerdict::BINARY, $verdict->reason);
    }

    #[Test]
    public function generated_files_are_detected_from_header_comments_only(): void
    {
        $policy = $this->policy();

        $this->assertSame(CodeVerdict::GENERATED, $policy->assessContent('a.go', "// Code generated by protoc-gen-go. DO NOT EDIT.\npackage a\n")->reason);
        $this->assertSame(CodeVerdict::GENERATED, $policy->assessContent('a.php', "<?php\n/** @generated */\nclass A {}\n")->reason);
        $this->assertSame(CodeVerdict::GENERATED, $policy->assessContent('a.py', "# auto-generated, do not touch\nx = 1\n")->reason);
        // A variable or string that merely MENTIONS it is not a header marker.
        $this->assertTrue($policy->assessContent('b.php', "<?php\n\$autoGenerated = true;\n\$note = 'DO NOT EDIT';\n")->accepted);
        // A marker deep in the file (past the header) is ignored.
        $deep = str_repeat("// line\n", 40)."// @generated\n";
        $this->assertTrue($policy->assessContent('c.js', $deep)->accepted);
    }

    #[Test]
    public function the_flag_can_be_skipped_for_jobs_already_queued(): void
    {
        $policy = $this->policy(false);

        $this->assertTrue($policy->assessContent('src/a.php', "<?php\nclass A {}\n", checkEnabled: false)->accepted);
        // ...but the deny-list is never skippable.
        $this->assertFalse($policy->assessContent('vendor/a.php', "<?php\nclass A {}\n", checkEnabled: false)->accepted);
    }
}
